def run_property(count: int, seed: int, with_arxo: bool, record: Path | None) -> int:
    cases = load_cases()
    calendar = load_calendar(cases)
    ref = Reference(calendar)
    rng = random.Random(seed)
    scopes = ["Gibel", "StoimostDetali", "VyborOtsenshchikov", "SrokiPunkta3"]
    generated = []
    for n in range(count):
        scope = scopes[n % len(scopes)]
        inputs = random_case(rng, scope)
        generated.append({"id": f"P{n:04d}", "scope": scope, "source": "property", "inputs": inputs,
                          "expected": ref.compute(scope, inputs), "rationale": f"seed={seed}"})
    failures = 0
    catala_log = []
    for case in generated:
        actual, error = run_catala(case["scope"], case["inputs"], calendar)
        problems = [error[:300]] if error else compare_outputs(case["expected"], actual)
        catala_log.append({"id": case["id"], "scope": case["scope"], "inputs": case["inputs"],
                           "expected": case["expected"], "catala": actual, "problems": problems})
        if problems:
            failures += 1
            print(f"FAIL catala {case['id']} {case['scope']} {json.dumps(case['inputs'])}: {'; '.join(problems)}")
    print(f"property/catala: {count - failures}/{count} random cases agreed with the Python oracle (seed {seed})")
    arxo_failures = 0
    arxo_report = None
    if with_arxo:
        rendered = render_suites({"cases": generated})
        with tempfile.TemporaryDirectory(prefix="parity-property-") as tmp:
            root = Path(tmp)
            # The calendar dataset is looked up upwards from the suite file as
            # artifact:corpus/clir/<name>, so the temporary root mirrors that layout.
            (root / "corpus" / "clir").mkdir(parents=True)
            for name in ("kz-official-2026.calendar.json", "kz-official-calendar-2026.lawir.json"):
                shutil.copyfile(CLIR_DIR / name, root / "corpus" / "clir" / name)
            (root / "tests").mkdir()
            engine = Arxo(root / "work") if (root / "work").mkdir() is None else None
            arxo_report = []
            for name, text in rendered.items():
                suite = root / "tests" / name
                suite.write_text(text, encoding="utf-8")
                report = engine.test([suite], "sroki" in name, name)
                arxo_report.append({"suite": name, "passed": report["passed"], "failed": report["failed"]})
                for item in report["tests"]:
                    if not item["passed"]:
                        arxo_failures += 1
                        print(f"FAIL arxo {item['title']}: {'; '.join(item['failures'])}")
        print(f"property/arxo: {count - arxo_failures}/{count} random cases agreed with the Python oracle (seed {seed})")
    if record:
        record.mkdir(parents=True, exist_ok=True)
        (record / f"property-seed{seed}.json").write_text(json.dumps(
            {"count": count, "seed": seed, "catala": {"agreed": count - failures, "cases": catala_log},
             "arxo": {"agreed": count - arxo_failures, "suites": arxo_report} if with_arxo else None},
            ensure_ascii=False, indent=2), encoding="utf-8")
    return 1 if (failures or arxo_failures) else 0


def record_catala(record: Path) -> None:
    """Catala outputs for the 65 reference cases, as evidence next to cases.json."""
    cases = load_cases()
    calendar = load_calendar(cases)
    out = []
    for case in cases["cases"]:
        actual, error = run_catala(case["scope"], case["inputs"], calendar)
        out.append({"id": case["id"], "scope": case["scope"], "catala": actual, "error": error or None,
                    "problems": compare_outputs(case["expected"], actual) if not error else [error[:300]]})
    record.mkdir(parents=True, exist_ok=True)
    version = subprocess.run([clerk_binary(), "--version"], capture_output=True, text=True, env=clerk_env())
    (record / "catala-parity.json").write_text(json.dumps(
        {"clerk": (version.stdout or version.stderr).strip().splitlines()[:1], "cases": out},
        ensure_ascii=False, indent=2), encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--emit", action="store_true")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--catala", action="store_true")
    parser.add_argument("--arxo", action="store_true")
    parser.add_argument("--property", type=int, metavar="N")
    parser.add_argument("--seed", type=int, default=1)
    parser.add_argument("--no-arxo", action="store_true", help="in --property, only Catala against the oracle")
    parser.add_argument("--all", action="store_true")
    parser.add_argument("--law", metavar="BINARY", help="law-cli (or the law wrapper); default $LAW_CLI or PATH")
    parser.add_argument("--record", type=Path, metavar="DIR", help="write JSON reports here")
    parser.add_argument("-v", "--verbose", action="store_true")
    args = parser.parse_args()
    if args.law:
        law_command(args.law)
    rc = 0
    if args.emit:
        rc |= emit(check=False)
    if args.check or args.all:
        rc |= emit(check=True)
    if args.catala or args.all:
        rc |= check_catala(args.verbose)
        if args.record:
            record_catala(args.record)
    if args.arxo or args.all:
        rc |= run_arxo(args.record)
    if args.property:
        rc |= run_property(args.property, args.seed, not args.no_arxo, args.record)
    if not any((args.emit, args.check, args.catala, args.arxo, args.property, args.all)):
        parser.print_help()
        return 2
    return rc


if __name__ == "__main__":
    raise SystemExit(main())
