def truth_expect(pred: str, value) -> str:
    status = {None: "NEITHER", True: "TRUE_ONLY", False: "FALSE_ONLY"}[value]
    return f"    evaluate truth({pred});\n    expect truth_status == {status};\n"


def value_expect(var: str, typ: str, pred_tpl: str, value, render) -> str:
    """Numeric/date output: exactly one value and it matches, or none at all."""
    out = (f"    evaluate collect {var}: {typ} where {pred_tpl.format(v=var)};\n"
           f"    expect result_kind == COLLECTION;\n")
    if value is None:
        return out + "    expect collected_count(0);\n"
    return (out + "    expect collected_count(1);\n"
            + f"    evaluate truth({pred_tpl.format(v=render(value))});\n    expect truth_status == TRUE_ONLY;\n")


def lawtest_case(case: dict) -> tuple[str, bool]:
    """Returns (test text, needs_calendar)."""
    i, x, scope = case["inputs"], case["expected"], case["scope"]
    facts: list[str] = []
    checks = ""
    a = facts.append
    if scope == "Gibel":
        a(f"raschet_po_ts({E['r']}, {E['ts']})")
        if i.get("tekhnicheski_nevozmozhno"):
            a(f"vosstanovlenie_tekhnicheski_nevozmozhno({E['ts']})")
        if i.get("ozhidaemye_raskhody") is not None:
            a(f"ozhidaemye_raskhody_na_vosstanovlenie({E['ts']}, {money(i['ozhidaemye_raskhody'])})")
        if i.get("rynochnaya_stoimost") is not None:
            a(f"rynochnaya_stoimost_na_datu_otcheta({E['ts']}, {money(i['rynochnaya_stoimost'])})")
        if i.get("ostatki_peredany") is True:
            a(f"ostatki_peredany_v_sobstvennost_strakhovshchika({E['r']})")
        elif i.get("ostatki_peredany") is False:
            a(f"not ostatki_peredany_v_sobstvennost_strakhovshchika({E['r']})")
        if i.get("stoimost_godnykh_ostatkov") is not None:
            a(f"stoimost_godnykh_k_realizatsii_ostatkov({E['ts']}, {money(i['stoimost_godnykh_ostatkov'])})")
        checks += truth_expect(f"vosstanovlenie_ekonomicheski_netselesoobrazno({E['ts']})", x["netselesoobrazno"])
        checks += truth_expect(f"ts_schitaetsya_unichtozhennym({E['ts']})", x["unichtozheno"])
        checks += value_expect("amount", "Money", f"strakhovaya_vyplata_pri_gibeli({E['r']}, {{v}})", x["vyplata"], money)
    elif scope == "StoimostDetali":
        a(f"detal_ts({E['d']}, {E['ts']})")
        if i.get("podlezhit_zamene"):
            a(f"detal_podlezhit_zamene({E['d']})")
        if i.get("vladelets") == "FizicheskoeLitso":
            a(f"vladelets_fizicheskoe_litso({E['ts']})")
        if i.get("vladelets") == "YuridicheskoeLitso":
            a(f"vladelets_yuridicheskoe_litso({E['ts']})")
        if i.get("ne_podlezhit_tekhosmotru"):
            a(f"ne_podlezhit_obyazatelnomu_tekhosmotru({E['ts']})")
        if i.get("na_garantiynom_obsluzhivanii"):
            a(f"nakhoditsya_na_garantiynom_obsluzhivanii({E['ts']})")
        if i.get("srednegodovoy_probeg_km") is not None:
            a(f"srednegodovoy_probeg({E['ts']}, {i['srednegodovoy_probeg_km']} km)")
        if i.get("ranee_ne_povrezhdalas"):
            a(f"detal_ranee_ne_povrezhdalas({E['d']})")
        if i.get("ne_podvergalas_remontu"):
            a(f"detal_ne_podvergalas_remontu({E['d']})")
        if i.get("stoimost_novoy") is not None:
            a(f"rynochnaya_stoimost_novoy_detali({E['d']}, {money(i['stoimost_novoy'])})")
        if i.get("stoimost_s_uchetom_iznosa") is not None:
            a(f"stoimost_detali_s_uchetom_iznosa({E['d']}, {money(i['stoimost_s_uchetom_iznosa'])})")
        checks += truth_expect(f"detal_otsenivaetsya_bez_iznosa({E['d']})", x["bez_iznosa"])
        checks += value_expect("amount", "Money", f"stoimost_zamenyaemoy_detali({E['d']}, {{v}})", x["stoimost"], money)
    elif scope == "VyborOtsenshchikov":
        if i.get("predlozheno") is not None:
            a(f"predlozheno_otsenshchikov({E['r']}, {i['predlozheno']})")
        checks += truth_expect(f"vybor_otsenshchikov_obespechen({E['r']})", x["obespechen"])
    elif scope == "DopustimostOsmotra":
        names = {"dostup_besprepyatstvennyy": "dostup_k_ts_besprepyatstvennyy", "identifikatsiya_provodima": "identifikatsiya_ts_provodima",
                 "probeg_ustanovim": "probeg_po_odometru_ustanovim", "komplektnost_ustanovima": "komplektnost_ustanovima",
                 "perechen_defektov_ustanovim": "perechen_defektov_ustanovim", "fotosemka_provodima": "fotosemka_povrezhdeniy_provodima",
                 "priznaki_remontov_ustanovimy": "priznaki_prezhnikh_remontov_ustanovimy"}
        for key, pred in names.items():
            if i.get(key):
                a(f"{pred}({E['r']})")
        for key, pred in (("opredelyaetsya_stoimost_remonta", "opredelyaetsya_stoimost_vosstanovitelnogo_remonta"),
                          ("dokumenty_o_dtp", "dokumenty_o_povrezhdeniyakh_v_dtp_predstavleny")):
            if i.get(key) is True:
                a(f"{pred}({E['r']})")
            elif i.get(key) is False:
                a(f"not {pred}({E['r']})")
        checks += truth_expect(f"osmotr_vozmozhen({E['r']})", x["vozmozhen"])
        checks += truth_expect(f"osmotr_dopustim({E['r']})", x["dopustim"])
    elif scope == "SrokiPunkta3":
        a(f"poterpevshiy_po_raschetu({E['r']}, {E['p']})")
        if i.get("uproshchennoe_oformlenie"):
            a(f"uproshchennoe_oformlenie_proisshestviya({E['r']})")
        if i.get("otchet_poluchen"):
            a(f"otchet_poluchen_poterpevshim({E['r']}, @{i['otchet_poluchen']})")
        if i.get("otmetka_nesoglasiya_poluchena"):
            a(f"otmetka_nesoglasiya_poluchena_strakhovshchikom({E['r']}, @{i['otmetka_nesoglasiya_poluchena']})")
        if i.get("osmotr_osushchestvlen"):
            a(f"osmotr_osushchestvlen_strakhovshchikom({E['r']}, @{i['osmotr_osushchestvlen']})")
        if i.get("otchet_predostavlen") is True:
            a(f"otchet_predostavlen_poterpevshemu({E['r']})")
        elif i.get("otchet_predostavlen") is False:
            a(f"not otchet_predostavlen_poterpevshemu({E['r']})")
        if i.get("den_rassmotreniya"):
            a(f"den_rassmotreniya_dela({E['r']}, @{i['den_rassmotreniya']})")
        date = lambda v: f"@{v}"  # noqa: E731
        checks += value_expect("day", "Date", f"predel_otmetki_poterpevshego({E['r']}, {{v}})", x["predel_otmetki"], date)
        checks += value_expect("day", "Date", f"predel_otveta_strakhovshchika({E['r']}, {{v}})", x["predel_otveta"], date)
        checks += value_expect("day", "Date", f"predel_predostavleniya_otcheta({E['r']}, {{v}})", x["predel_otcheta"], date)
        checks += truth_expect(f"otchet_ne_predostavlen_v_srok({E['r']})", x["otchet_ne_v_srok"])
        checks += truth_expect(f"pravo_na_vyplatu_po_punktu_3_1_stati_22_zakona({E['p']}, {E['r']})", x["pravo_na_vyplatu"])
    elif scope == "ItogovayaVelichina":
        if i.get("summa") is not None:
            a(f"itogovaya_stoimost_v_tenge({E['o']}, {money(i['summa'])})")
        if i.get("rasshifrovana_propisyu"):
            a(f'otchet_summa_propisyu({E["o"]}, "образец")')
        checks += truth_expect(f"otchet_soderzhit_itogovuyu_velichinu({E['o']})", x["nadlezhashche"])
    else:
        raise SystemExit(f"unknown scope {scope}")
    calendar = scope == "SrokiPunkta3"
    body = "".join(f'        assert {fact} {{ id "{case["id"]}-a{n}"; origin case_input; }}\n' for n, fact in enumerate(facts))
    text = (f"// {case['id']} — {case['source']}: {case['rationale']}\n"
            f'test "urn:query:vred-parity:{case["id"]}" {{\n    given {{\n'
            + (CONTEXT_CAL if calendar else CONTEXT_NO_CAL) + body + "    }\n" + checks + "}\n\n")
    return text, calendar


def render_suites(cases: dict) -> dict[str, str]:
    plain, cal = HEADER.format(version="0.2"), HEADER.format(version="0.1") + PROFILE
    for case in cases["cases"]:
        text, calendar = lawtest_case(case)
        if calendar:
            cal += text
        else:
            plain += text
    return {"parity.lawtest": plain, "parity-sroki.lawtest": cal}


def emit(check: bool) -> int:
    rendered = render_suites(load_cases())
    PARITY_DIR.mkdir(exist_ok=True)
    stale = []
    for name, text in rendered.items():
        path = PARITY_DIR / name
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            path.write_text(text, encoding="utf-8")
            print(f"emitted {path.relative_to(ROOT)}")
    if check and stale:
        print(f"parity suites stale: {stale}; run --emit", file=sys.stderr)
        return 1
    if check:
        print("parity suites: up to date")
    return 0


