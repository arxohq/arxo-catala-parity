#!/usr/bin/env python3
"""Parity runner: Catala 1.2 <-> Arxo Law on the same cases of one regulation.

    python3 parity.py --check            # tests/parity/*.lawtest are up to date with cases.json
    python3 parity.py --emit             # regenerate them from cases.json
    python3 parity.py --catala           # Catala model against the 65 reference cases
    python3 parity.py --arxo             # Arxo engine (law-cli) on the same 65 cases, two suites
    python3 parity.py --property 120 --seed 1   # random cases: Python oracle <-> Catala <-> Arxo
    python3 parity.py --all              # check + catala + arxo
    python3 parity.py --all --record results    # also write the JSON reports

Everything here is standard-library Python (3.12+). The two external tools are

* `clerk` from Catala 1.2.x (`opam install catala.1.2.0`); found on PATH or in
  ~/.opam/*/bin;
* `law-cli`, the Arxo engine binary, given by `--law`, by `$LAW_CLI`, or found on
  PATH (the `law` wrapper is accepted too: subcommands are prefixed with `engine`).

Semantics of the comparison are documented in catala/README.md. The Arxo side
runs the package in `corpus/laws/kz/regulators/vred-ts/` exactly as the engine runs any package: the
sources are lowered with the pinned imports context, the calendar snapshot is
added to the world of the deadline suite, and `law-cli test` evaluates the
scenarios. No Arxo code of this repository computes any legal answer.
"""
