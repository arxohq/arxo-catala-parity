def clerk_binary() -> str:
    found = shutil.which("clerk")
    if found:
        return found
    for candidate in sorted(Path.home().glob(".opam/*/bin/clerk")):
        return str(candidate)
    raise SystemExit("clerk (Catala 1.2) not found: opam install catala.1.2.0")


_PROJECT: Path | None = None


def clerk_project() -> Path:
    """Temporary copy of the model with its OWN `_build` next to it.

    `clerk` keeps the standard library in `_build/libcatala` RELATIVE to the
    project and re-checks it on every run when `CLERK_BUILD_DIR` is moved
    out: a 09.09.2026 measurement showed 2.0-3.7s against 0.04s for a warm
    in-project `_build`, i.e. fifty times more expensive for nothing.
    The package directory stays clean either way: the copy lives in the
    process's temporary directory.
    """
    global _PROJECT
    if _PROJECT is None:
        _PROJECT = Path(tempfile.mkdtemp(prefix="vred-ts-catala-"))
        shutil.copyfile(MODEL, _PROJECT / MODEL.name)
    return _PROJECT


def clerk_env() -> dict:
    """PATH with the opam switch's directory: building the stdlib needs `ocamlc`."""
    binary = Path(clerk_binary()).resolve()
    return dict(os.environ, PATH=f"{binary.parent}{os.pathsep}{os.environ.get('PATH', '')}")


def run_catala(scope: str, inputs: dict, calendar: dict) -> tuple[dict | None, str]:
    payload = dict(inputs)
    if scope == "SrokiPunkta3":
        payload["kalendar"] = calendar
    project = clerk_project()
    result = subprocess.run([clerk_binary(), "run", MODEL.name, f"--scope={scope}", "--input", json.dumps(payload),
                             "-F", "json", "--color=never"], capture_output=True, text=True,
                            cwd=project, env=clerk_env())
    if result.returncode != 0:
        return None, (result.stdout + result.stderr).strip()
    return json.loads(result.stdout), ""


def normalize(value):
    if isinstance(value, float):
        return Decimal(str(value)).normalize()
    if isinstance(value, (int,)) and not isinstance(value, bool):
        return Decimal(value).normalize()
    return value


def compare_outputs(expected: dict, actual: dict | None) -> list[str]:
    problems = []
    for key, want in expected.items():
        got = None if actual is None else actual.get(key)
        if normalize(want) != normalize(got):
            problems.append(f"{key}: expected {want!r}, Catala gave {got!r}")
    if actual is not None:
        for key in actual:
            if key not in expected:
                problems.append(f"{key}: extra Catala output {actual[key]!r}")
    return problems


def check_catala(verbose: bool) -> int:
    cases = load_cases()
    calendar = load_calendar(cases)
    failures = 0
    for case in cases["cases"]:
        actual, error = run_catala(case["scope"], case["inputs"], calendar)
        if error:
            failures += 1
            print(f"FAIL {case['id']} ({case['scope']}): Catala failed — {error[:400]}")
            continue
        problems = compare_outputs(case["expected"], actual)
        if problems:
            failures += 1
            print(f"FAIL {case['id']} ({case['scope']}): " + "; ".join(problems))
        elif verbose:
            print(f"PASS {case['id']} ({case['scope']}): {actual}")
    total = len(cases["cases"])
    print(f"catala: {total - failures}/{total} cases matched the cases.json expectations")
    return 1 if failures else 0


def random_case(rng: random.Random, scope: str) -> dict:
    def maybe(value, p=0.85):
        return value if rng.random() < p else None
    if scope == "Gibel":
        market = rng.choice([0, 1, rng.randint(1, 10_000_000), rng.randint(1, 10_000_000)])
        costs_choice = rng.random()
        costs = (market * 4 // 5 if costs_choice < 0.25 else market * 4 // 5 + 1 if costs_choice < 0.5
                 else rng.randint(0, 10_000_000))
        i = {"tekhnicheski_nevozmozhno": rng.random() < 0.3}
        if maybe(True) is not None:
            i["ozhidaemye_raskhody"] = costs
        if maybe(True) is not None:
            i["rynochnaya_stoimost"] = market
        per = rng.choice([True, False, None])
        if per is not None:
            i["ostatki_peredany"] = per
        if maybe(True, 0.7) is not None:
            i["stoimost_godnykh_ostatkov"] = rng.randint(0, 2_000_000)
        return i
    if scope == "StoimostDetali":
        i = {"podlezhit_zamene": rng.random() < 0.85, "ne_podlezhit_tekhosmotru": rng.random() < 0.6,
             "na_garantiynom_obsluzhivanii": rng.random() < 0.6, "ranee_ne_povrezhdalas": rng.random() < 0.85,
             "ne_podvergalas_remontu": rng.random() < 0.85}
        owner = rng.choice(["FizicheskoeLitso", "YuridicheskoeLitso", None])
        if owner:
            i["vladelets"] = owner
        km = rng.choice([15000, 15001, 20000, 20001, rng.randint(0, 40000), None])
        if km is not None:
            i["srednegodovoy_probeg_km"] = km
        if maybe(True) is not None:
            i["stoimost_novoy"] = rng.randint(1, 1_000_000)
        if maybe(True) is not None:
            i["stoimost_s_uchetom_iznosa"] = rng.randint(1, 1_000_000)
        return i
    if scope == "VyborOtsenshchikov":
        n = rng.choice([0, 1, 2, 3, rng.randint(0, 10), None])
        return {} if n is None else {"predlozheno": n}
    if scope == "SrokiPunkta3":
        def day():
            return (dt.date(2026, 1, 1) + dt.timedelta(days=rng.randint(-3, 370))).isoformat()
        i = {"uproshchennoe_oformlenie": rng.random() < 0.15}
